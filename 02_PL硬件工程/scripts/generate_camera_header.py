"""Generate the standalone SCCB table from the shared VGA JSON configuration."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def main():
    d=json.loads((ROOT/'config/ov5640_vga_rgb565.json').read_text())
    rows=d['base_registers']+d['overrides']
    text='/* Generated by scripts/generate_camera_header.py; do not edit manually. */\n#ifndef OV5640_VGA_REGS_H\n#define OV5640_VGA_REGS_H\nstruct camera_reg { unsigned short address; unsigned char value; unsigned short delay_ms; };\nstatic const struct camera_reg camera_regs[] = {\n'
    text+=''.join('    {%s, %s, %d},\n'%(r['address'],r['value'],r['delay_ms']) for r in rows)
    text+='};\n#define CAMERA_REG_COUNT (sizeof(camera_regs)/sizeof(camera_regs[0]))\n#endif\n'
    (ROOT/'sdk/ov5640_vga_regs.h').write_text(text)
    print('Generated',len(rows),'SCCB writes')
if __name__=='__main__': main()
