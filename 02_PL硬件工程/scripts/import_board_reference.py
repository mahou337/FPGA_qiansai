"""Extract reviewed board inputs from user-supplied reference IP (read-only)."""
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
ROOT = Path(__file__).resolve().parents[1]
WORKSPACE = ROOT.parent
NS = '{http://www.spiritconsortium.org/XMLSchema/SPIRIT/1685-2009}'
SOURCES = {
    'network': WORKSPACE / '10_PS_EMIO_NET_TEST/NET_TEST/NET_TEST.srcs/sources_1/bd/ZYNQ/ip/ZYNQ_processing_system7_0_0/ZYNQ_processing_system7_0_0.xci',
    'bram': WORKSPACE / '15_PS_BRAM_TEST/PS_BRAM_TEST/PS_BRAM_TEST.srcs/sources_1/bd/ZYNQ_CORE/ip/ZYNQ_CORE_processing_system7_0_0/ZYNQ_CORE_processing_system7_0_0.xci',
}
def read_parameters(path):
    values = {e.attrib.get(NS+'referenceId', ''): e.text
              for e in ET.parse(path).getroot().iter() if e.tag.endswith('configurableElementValue')}
    return {k.removeprefix('PARAM_VALUE.'): v for k,v in values.items() if k.startswith('PARAM_VALUE.')}
def main():
    refs = {name: read_parameters(path) for name,path in SOURCES.items()}
    bram = refs['bram']
    assert bram['PCW_PACKAGE_NAME'] == 'clg484'
    assert bram['PCW_UIPARAM_DDR_BUS_WIDTH'] == '16 Bit'
    assert bram['PCW_UIPARAM_DDR_DEVICE_CAPACITY'] == '4096 MBits'
    # Package lengths / package delays are device-derived; let Vivado regenerate them.
    settings = {k:v for k,v in bram.items() if k.startswith('PCW_UIPARAM_DDR_') and '_PACKAGE_LENGTH' not in k}
    for key in ('PCW_PACKAGE_NAME', 'PCW_CRYSTAL_PERIPHERAL_FREQMHZ',
                'PCW_APU_PERIPHERAL_FREQMHZ', 'PCW_DDR_PERIPHERAL_CLKSRC',
                'PCW_PRESET_BANK0_VOLTAGE', 'PCW_PRESET_BANK1_VOLTAGE',
                'PCW_UART_PERIPHERAL_FREQMHZ', 'PCW_UART0_BAUD_RATE'):
        settings[key] = bram[key]
    lines = ['# Generated by scripts/import_board_reference.py; source: 15_PS_BRAM_TEST.',
             '# Reviewed reference values, NOT a claim of physical boot/memory testing.',
             '# Do not import network example clg400 package metadata into clg484.',
             'set BOARD_CONFIG_SOURCE {15_PS_BRAM_TEST}',
             'set BOARD_CONFIG_VERIFIED 0', 'set_property -dict [list \\']
    for key,value in sorted(settings.items()):
        assert not any(c in value for c in '{}\\\n\r')
        lines.append(' CONFIG.'+key+' {'+value+'} \\')
    lines.extend(['] [get_bd_cells ps7]',
        '# SD0 is an application addition based on the schematic; absent in both examples.',
        'set_property -dict [list \\',
        ' CONFIG.PCW_SD0_PERIPHERAL_ENABLE {1} \\',
        ' CONFIG.PCW_SD0_SD0_IO {MIO 40 .. 45} \\',
        ' CONFIG.PCW_SD0_GRP_CD_ENABLE {1} \\',
        ' CONFIG.PCW_SD0_GRP_CD_IO {MIO 47} \\',
        ' CONFIG.PCW_SD0_GRP_WP_ENABLE {0} \\',
        '] [get_bd_cells ps7]'])
    (ROOT/'config/board_reference.tcl').write_text('\n'.join(lines)+'\n', encoding='utf8')
    differences = {k:{name: ps.get(k) for name,ps in refs.items()}
        for k in sorted(set(refs['network']) | set(bram))
        if refs['network'].get(k) != bram.get(k)}
    provenance = {'source_files': {name:{'path':str(path.relative_to(WORKSPACE)),
        'sha256':hashlib.sha256(path.read_bytes()).hexdigest()} for name,path in SOURCES.items()},
        'selected_reference':'bram', 'physical_validation':False,
        'imported_settings':settings, 'all_reference_differences':differences,
        'application_overrides':{'UART':'UART0 EMIO 115200', 'FCLK0_MHz':50,
        'M_AXI_GP0':True, 'SD0':'MIO40..45, CD47; not demonstrated by references',
        'Ethernet':'disabled in current gesture design'}}
    (ROOT/'config/board_reference_provenance.json').write_text(json.dumps(provenance,indent=2)+'\n')
    print('Imported',len(settings),'board settings from BRAM reference')
if __name__ == '__main__': main()
